#!/usr/bin/env python3
"""Energy budget of merging: magnetic energy per proton inside merged ICMEs at 1 au compared with the upper limit on extra proton
heating (temperature excess at fixed expansion and speed, paper/numbers.json), and the heliocentric distance inside which released
energy must have been deposited to stay below that limit after adiabatic cooling.

Radial scalings inside ICMEs (Wang, Du & Richardson 2005): n ~ R^-2.4, B ~ R^-1.5, so B^2/n ~ R^-0.6.
Heat deposited at R cools adiabatically (gamma = 5/3): T ~ n^(2/3) ~ R^-1.6. Energy per proton deposited at R and observed at 1 au:
  dE(1 au) = f wB(1 au) R^-0.6 R^1.6 = f wB(1 au) R      ->  R_max = dE_lim / (f wB(1 au)).
Local heating in a reconnection exhaust: k dT ~ 0.13 m_p v_A^2 (Phan et al. 2014)."""
import json
from pathlib import Path
import numpy as np, pandas as pd

B = Path(__file__).resolve().parent
e, mp, mu0, kB = 1.602e-19, 1.673e-27, 4e-7 * np.pi, 1.381e-23
X = pd.read_csv(B / "icme_plasma.csv"); X = X[X.dur_h >= 6]
NUM = json.load(open(B / "paper/numbers.json"))
X["wB"] = (X.B * 1e-9) ** 2 / (2 * mu0) / (X.N * 1e6) / e                     # eV per proton
X["Eth"] = 1.5 * kB * X["T"] / e                                                # eV per proton (protons only)
X["vA"] = X.B * 1e-9 / np.sqrt(mu0 * X.N * 1e6 * mp) / 1e3                      # km/s
M, S = X[X.ncme >= 2], X[X.ncme == 1]
wB, Eth, vA = M.wB.median(), M.Eth.median(), M.vA.median()
lim = (10 ** NUM["Texchi"] - 1) * Eth                                           # upper limit on extra heat per proton, eV
f = NUM["fann"] / 100; fE = (f, 1 - (1 - f) ** 2)                               # fraction of magnetic energy released (flux ~ f, energy ~ flux^2)
rel = [x * wB for x in fE]
rmax = [lim / r for r in rel]
exh = 0.13 * mp * (vA * 1e3) ** 2 / e
out = dict(enWB=wB, enWBs=S.wB.median(), enEth=Eth, enLim=lim, enRelLo=rel[0], enRelHi=rel[1], enRmaxLo=min(rmax), enRmaxHi=max(rmax),
           enVA=vA, enExh=exh, enExhT=exh * e / kB / 1e4, enTM=M["T"].median() / 1e4)
for k, v in out.items(): print(f"{k:9s} {v:.3g}")
with open(B / "paper/macros_energy.tex", "w") as fh:
    fh.write("% generated by 05_energy.py\n")
    for k, v in out.items():
        s = f"{v:.0f}" if v >= 10 else (f"{v:.1f}" if v >= 1 else f"{v:.2f}")
        fh.write(f"\\newcommand{{\\{k}}}{{{s}}}\n")
