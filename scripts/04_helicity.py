#!/usr/bin/env python3
"""Axial flux, azimuthal flux and magnetic helicity of magnetic clouds in single and merged ICMEs from Lundquist fits.

The fits (04a_lundquist_fit.js, hourly OMNI GSE field) give axis direction, impact parameter p (in units of R), axial field B0,
handedness H and a centre shift s0. The radius follows from the duration, the mean speed and the geometry,
R = V dt sin(gamma) / (2 sqrt(1 - p^2)), gamma = angle between the axis and the Sun-Earth line. Then (x0 = 2.405, length 1 au):
  axial flux        Phi_z  = 2 pi B0 R^2 J1(x0)/x0
  azimuthal flux    Phi_az = B0 R L / x0
  helicity          H      = (4 pi B0^2 R^3 L / x0) int_0^1 J1(x0 s)^2 s ds
Coalescence of parallel ropes removes azimuthal flux at the interface while axial flux adds and helicity is nearly conserved;
erosion by reconnection with the ambient field removes azimuthal flux and helicity together."""
import json
from pathlib import Path
import numpy as np, pandas as pd
from scipy.special import j1
from scipy.integrate import quad
from scipy.stats import mannwhitneyu

B = Path(__file__).resolve().parent
AU, X0 = 1.496e8, 2.405
I1 = quad(lambda s: j1(X0 * s) ** 2 * s, 0, 1)[0]
X = pd.read_csv(B / "icme_plasma.csv", dtype={"start": str, "end": str, "dist": str})
L = pd.DataFrame([r.split(",") for r in open(B / "lundquist_raw.txt").read().strip().split(";")],
                 columns=["start", "chi", "th", "ph", "p", "B0", "s0", "H", "Vm", "nh"])
for c in L.columns[1:]: L[c] = pd.to_numeric(L[c], errors="coerce")
L = L.merge(X[["start", "ncme", "mc", "dur_h"]], on="start")
out = []
for r in L.itertuples():
    th = float(np.clip(r.th, -np.pi / 2, np.pi / 2)); p = float(np.clip(r.p, 0, 0.95)); b0 = abs(r.B0)
    ax = np.array([np.cos(th) * np.cos(r.ph), np.cos(th) * np.sin(r.ph), np.sin(th)])
    chord = r.Vm * r.dur_h * 3600 / AU
    R = chord * np.sqrt(max(1 - ax[0] ** 2, 1e-3)) / (2 * np.sqrt(1 - p ** 2))
    Rcm, B0G, Lcm = R * AU * 1e5, b0 * 1e-5, AU * 1e5
    out.append(dict(start=r.start, ncme=r.ncme, mc=r.mc, chi=r.chi, p=p, B0=b0, H=r.H, s0=r.s0, axis_x=ax[0], lat=np.degrees(th), R_au=R,
                    phi_z=2 * np.pi * B0G * Rcm ** 2 * j1(X0) / X0 / 1e21,          # 1e21 Mx
                    phi_az=B0G * Rcm * Lcm / X0 / 1e21,                           # 1e21 Mx per au of length
                    hel=4 * np.pi * B0G ** 2 * Rcm ** 3 * Lcm / X0 * I1 / 1e42))   # 1e42 Mx^2 per au of length
F = pd.DataFrame(out); F.to_csv(B / "lundquist_fits.csv", index=False)
good = F[(F.chi < 0.35) & (F.p < 0.8) & (np.abs(F.axis_x) < 0.8) & (np.abs(F.s0) < 0.29)]
print(f"fits {len(F)} (single {int((F.ncme == 1).sum())}, merged {int((F.ncme >= 2).sum())}); acceptable {len(good)}; "
      f"handedness +1 fraction {np.mean(F.H > 0):.2f}")
res = {}
for sel, lab in ((F, "all"), (good, "good"), (F[F.mc == 2], "MC"), (good[good.mc == 2], "good_MC")):
    s, m = sel[sel.ncme == 1], sel[sel.ncme >= 2]
    line = f"[{lab}] single {len(s)}, merged {len(m)}"
    for c in ("phi_z", "phi_az", "hel", "B0", "R_au", "chi"):
        if len(m) >= 3:
            rt = m[c].median() / s[c].median(); pv = mannwhitneyu(s[c], m[c]).pvalue
            line += f"\n   {c:7s}: single {s[c].median():8.3g}, merged {m[c].median():8.3g}, ratio {rt:5.2f}, p {pv:.3f}"
            res[f"{lab}_{c}"] = dict(single=float(s[c].median()), merged=float(m[c].median()), ratio=float(rt), p=float(pv), ns=len(s), nm=len(m))
    for c in ("phi_z", "phi_az", "hel"):
        d = sel[[c, "ncme"]].dropna(); d = d[d[c] > 0]
        if len(d) < 10 or d.ncme.nunique() < 2: continue
        lx, ly = np.log(d.ncme.values), np.log(d[c].values); a0 = np.polyfit(lx, ly, 1)[0]
        rng = np.random.default_rng(1); bs = []
        for _ in range(3000):
            i = rng.integers(0, len(d), len(d))
            if np.ptp(lx[i]) > 0: bs.append(np.polyfit(lx[i], ly[i], 1)[0])
        lo, hi = np.percentile(bs, [2.5, 97.5]); line += f"\n   {c} ~ N^{a0:.2f} ({lo:.2f}..{hi:.2f})"
        res[f"{lab}_{c}_exp"] = dict(a=float(a0), lo=float(lo), hi=float(hi))
    print(line)
json.dump(res, open(B / "helicity.json", "w"), indent=1)

# macros for the paper: fit quality of single vs merged clouds (the model assumes one relaxed flux rope)
s, m = F[F.ncme == 1], F[F.ncme >= 2]
M = dict(lqNs=len(s), lqNm=len(m), lqChiS=s.chi.median(), lqChiM=m.chi.median(), lqChiP=mannwhitneyu(s.chi, m.chi).pvalue,
         lqGoodS=100 * (s.chi < 0.35).mean(), lqGoodM=100 * (m.chi < 0.35).mean(),
         lqHelR=res["all_hel"]["ratio"], lqHelP=res["all_hel"]["p"], lqPhizR=res["all_phi_z"]["ratio"], lqPhizP=res["all_phi_z"]["p"])
fmt = lambda k, v: str(int(v)) if k in ("lqNs", "lqNm") else (f"{v:.0f}" if k.startswith("lqGood") else (f"{v:.2g}" if k.endswith("P") else f"{v:.2f}"))
with open(B / "paper/macros_hel.tex", "w") as fh:
    fh.write("% generated by 04_helicity.py\n")
    for k, v in M.items(): fh.write(f"\\newcommand{{\\{k}}}{{{fmt(k, v)}}}\n")
print(open(B / "paper/macros_hel.tex").read())
