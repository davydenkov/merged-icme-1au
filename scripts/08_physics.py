#!/usr/bin/env python3
"""Physical time scales of merged and single ICMEs at 1 au and geoeffectiveness.
Alfven crossing time of the radial size, tau_A = D / v_A; transit time from the Sun, t_tr = 1 au / V; their ratio is the number of
Alfven times available for relaxation. Size grows as R^0.6 (Wang et al. 2005: x2.7 between 1 and 5 au), v_A ~ B n^-1/2 ~ R^-0.3,
so tau_A ~ R^0.9 and t_tr ~ R: the ratio changes little with distance. Total pressure (magnetic + proton thermal) and Dst minimum."""
from pathlib import Path
import numpy as np, pandas as pd
from scipy.stats import mannwhitneyu
B = Path(__file__).resolve().parent
AU, mu0, mp, kB = 1.496e8, 4e-7 * np.pi, 1.673e-27, 1.381e-23
X = pd.read_csv(B / "icme_plasma.csv"); X = X[(X.dur_h >= 6) & (X.ncme >= 1)].copy()
X["D"] = X.V * X.dur_h * 3600                                                 # km
X["vA"] = X.B * 1e-9 / np.sqrt(mu0 * X.N * 1e6 * mp) / 1e3
X["tauA_d"] = X.D / X.vA / 86400; X["ttr_d"] = AU / X.V / 86400; X["NA"] = X.ttr_d / X.tauA_d
X["Pt"] = ((X.B * 1e-9) ** 2 / (2 * mu0) + X.N * 1e6 * kB * X["T"]) * 1e12     # pPa
X["shPt"] = ((X.shB * 1e-9) ** 2 / (2 * mu0) + X.shN * 1e6 * kB * X.shT) * 1e12
S, M = X[X.ncme == 1], X[X.ncme >= 2]
out = {}
for c, k in (("D", "phD"), ("vA", "phVA"), ("tauA_d", "phTau"), ("ttr_d", "phTtr"), ("NA", "phNA"), ("Pt", "phPt"), ("shPt", "phShPt"), ("dst", "phDst")):
    s, m = S[c].dropna(), M[c].dropna(); p = mannwhitneyu(s, m).pvalue
    out[k + "S"], out[k + "M"], out[k + "P"] = s.median(), m.median(), p
    print(f"{c:7s} single {s.median():10.3g} merged {m.median():10.3g}  p {p:.3f}  (n {len(s)}, {len(m)})")
out["phDstFracS"] = 100 * (S.dst.dropna() <= -100).mean(); out["phDstFracM"] = 100 * (M.dst.dropna() <= -100).mean()
from scipy.stats import fisher_exact
ss, mm = S.dst.dropna(), M.dst.dropna()
out["phStormP"] = fisher_exact([[int((mm <= -100).sum()), int((mm > -100).sum())], [int((ss <= -100).sum()), int((ss > -100).sum())]])[1]
out["phStormNM"], out["phStormNS"], out["phNdstM"], out["phNdstS"] = int((mm <= -100).sum()), int((ss <= -100).sum()), len(mm), len(ss)
# fraction of the poloidal flux removed by steady reconnection at rate eps*vA over the transit, merging starting at R0 (au)
for R0, k in ((0.05, "phRecA"), (0.3, "phRecB")): out[k] = 0.1 * 2.405 * out["phNAM"] * 10 * (1 - R0 ** 0.1)
print("Dst<=-100 fraction single %.0f%% merged %.0f%%" % (out["phDstFracS"], out["phDstFracM"]))
def fmt(k, v):
    if k in ("phStormNM", "phStormNS", "phNdstM", "phNdstS"): return str(int(v))
    if k.startswith("phRec"): return f"{v:.2f}"
    if k.endswith("P"): return f"{v:.2g}" if v >= 0.001 else r"{<}0.001"
    if k.startswith("phD") and not k.startswith("phDst"): return f"{v / 1e6:.0f}"   # 10^6 km
    return f"{v:.0f}" if abs(v) >= 10 else f"{v:.1f}"
with open(B / "paper/macros_phys.tex", "w") as fh:
    fh.write("% generated by 08_physics.py\n")
    for k, v in out.items(): fh.write(f"\\newcommand{{\\{k}}}{{{fmt(k, v)}}}\n")
